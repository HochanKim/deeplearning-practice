rng = np.random.RandomState(42)

# 0~199 를 무작위로 섞은 순서표. permutation = "섞어라"
순서 = rng.permutation(len(X))

# 200 × 0.7 = 140.0 → int()로 소수점 버려 140
n_train = int(len(X) * 0.7)

# 섞은 순서의 앞 140개 번호 = 학습용, 뒤 60개 번호 = 시험용 (00 미리보기 ⑥ 슬라이스)
tr, te = 순서[:n_train], 순서[n_train:]

# 문법 X[번호 리스트] = 그 번호의 행들만 골라 새 표를 만듦 (팬시 인덱싱)
X_train, X_test = X[tr], X[te]

# 정답도 '같은 번호'로 골라야 짝이 안 어긋납니다. 이게 제일 중요.
y_train, y_test = y[tr], y[te]
print("\n[2] 학습용", len(tr), "대 / 시험용", len(te), "대")

# 01 파일에서는 X가 200개 짜리 한 줄 (200, 4)
# => 설비당 답 하나 나옴

# 200 문제짜리 문제집이 있는데 140문제 공부하고, 나머지 60문제는 봉투에 넣어 봉인 => 시험 볼 때만 뜯음
# => 01 파일에서 봤다, 배운 걸 다시 물어보면 만점이 나온다 => 실력보다 기억력으로 판단되는 것

# 파일이 날짜 또는 설비순으로 정렬돼 있으면, 앞 140인 1월, 뒤 60은 12월 자료로 나눠질 수 있다
# => 그렇게 되면 시험이 편향된다
# => "현장 데이터는 거의 항상 정렬돼 있다, 섞는 걸 잊지 말아라"

# 7:3 비율은 관습, 8:2를 사용하는 경우도 많다, 데이터가 적을수록 학습용을 더 챙긴다

