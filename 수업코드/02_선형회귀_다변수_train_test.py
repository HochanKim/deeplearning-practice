print("    1번 설비의 정답:", y[0])
# 읽는 법: X는 200명 학생의 "국 영 수 과" 점수표 (비유), y는 그 학생들의 '내신 등급'과 같은 것
# => 한 행이 한 학생(=> 설비), 한 열이 한 과목(=> 센서)

# =====================================================================
# 2. 학습용 / 시험용 나누기 — 시험 문제를 미리 보지 않기
# =====================================================================
# 01 파일에서는 '200대 전부로 배우고, 200대 전부로 채점' => (비유) 마치 '답안지 보고 푼 시험'이라 점수를 신뢰하기 어려움
# => 그래서 시작하자마자 30%를 떼어 금고에 넣고, 마지막 채점에만 꺼낸다 => 학습 중엔 절대 안 봄

# train(학습용) = 배우는데 쓰는 데이터 (like 교과서)
# test(시험용) = 배운 적 없는 데이터로 실력을 재는 데 쓰는 데이터 (like 시험지)
# 일반화 = "안 본 데이터"에서도 맞히는 능력, 우리가 진짜 원하는 것 => 시험용 점수가 척도
# => 왜냐 현장에 들어가는 순간부터 들어오는 데이터는 전부 '안 본 데이터'

# 변수 'rng'는? => 무작위 기계에 번호(42)를 붙이면, 몇 번 돌려도 같은 무작위가 나옴
