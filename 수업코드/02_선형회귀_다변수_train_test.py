# 3. 표준화 — 열마다 따로, 그리고 학습용의 평균·표준편차만 써서
# =====================================================================
# 네 개의 센서의 숫자 크기는 제각각
print(
    "\n[3] 열별 원래 크기 (학습용 평균):", X_train.mean(axis=0).round(1)
)  # axis=0 (열) // axis=1 (행)
# 학습용 평균을 보면?
# => axis=0 "세로 방향으로": 열마다 하나씩 (4열이니 평균 값이 4개 나옴)
# 온도 300, 회전수 1400, 토크 40, 마모 120: 전부 다릅니다

# 표준화 없이 그냥 걸으면 어떻게 되나? => 01 파일에서 확인한 발산 현상이 심해진다 (손잡이가 4개라 튕길 방향도 4개)


def 손실_원래눈금(X, y, w, b):
    return np.mean((y - (X @ w + b)) ** 2)


print("=" * 70)
print("    표준화 안 하고 20걸음 걸어 보기:")
for lr in [0.1, 0.0000001]:
    w0, b0 = np.zeros(4), 0.0
    for _ in range(20):
        gw = np.array(
            [
                (
                    손실_원래눈금(X_train, y_train, w0 + np.eye(4)[j] * 1e-4, b0)
                    - 손실_원래눈금(X_train, y_train, w0 - np.eye(4)[j] * 1e-4, b0)
                )
                / 2e-4
                for j in range(4)
            ]
        )
        gb = (
            손실_원래눈금(X_train, y_train, w0, b0 + 1e-4)
            - 손실_원래눈금(X_train, y_train, w0, b0 - 1e-4)
        ) / 2e-4
        w0, b0 = w0 - lr * gw, b0 - lr * gb
    print(
        f"      lr={lr:<10} → 손실 {손실_원래눈금(X_train, y_train, w0, b0):.2e}"
    )  # {:.2e} = 지수 표기 (1.18e+39 = 1.18 × 10³⁹)
# lr = 0.1 -> 손실이 10의 39제곱, 발산(튕겨 나감). 회전수 1500이 곱한 것의 값이 너무 커짐
# lr = 0.000001 -> 안 튕기긴 하는데 손실 1106, 20걸음으로는 어림도 없음 (굼벵이 속도)
# 온도쪽은 그 lr로 너무 작아서 => 즉, '회전수에 맞는 보폭'과 '온도에 맞는 보폭'이 다른데 학습률은 하나 뿐 -> 어느 쪽에 맞춰도 망함
# 해결: 열마다 자를 똑같이 맞춘다 -> 열별 표준화, 그러면 lr 하나(0.1)로 다 됨

mu = X_train.mean(axis=0)  # 열별 평균 4개 <- 학습용으로만 계산
sd = X_train.std(axis=0)  # 열별 표준편차 4개 (퍼진 정도)

# 열마다 (값 − 그 열 평균) ÷ 그 열 표준편차 => 각각 표준화. numpy 가 열 맞춰 알아서 해 줍니다
Z_train = (X_train - mu) / sd

# 시험용도 '학습용의 mu(평균), sd(표준편차)'로 변환
Z_test = (X_test - mu) / sd

# 왜 시험용은 시험용 평균으로 안 하나? (두 가지 이유)
# => ① 시험용 정보가 학습에 새어 들어가면(누수) 점수가 부풀려진다 -> "시험 문제 미리 보지 않기"의 연장성
# => ② 현장에선 세 데이터가 한 줄씩 들어옴 -> 한 줄로 평균을 낼 수 없으니 어차피 학습때 자를 계속 써야 함

print("표준화 후 학습용 열별 평균:", np.abs(Z_train.mean(axis=0)).round(3), "← 전부 0")
print("표준화 후 학습용 열별 퍼짐:", Z_train.std(axis=0).round(3), "← 전부 1")
print(
    "표준화 후 시험용 열별 평균:",
    Z_test.mean(axis=0).round(3),
    "← 0 이 아님. 학습용 자를 빌려 썼으니 당연",
)


# =====================================================================
# 4. 예측과 학습 — 01 과 똑같고, w 가 숫자 하나에서 '숫자 4개'가 될 뿐
# =====================================================================

# 설비 한 대의 예측 = w1xz1 + w1xz2 + w3xz3 + w4xz4 + b ("센서값에 가중치 곱해서 다 더하기")
# 이걸 140대에 대해 한 번에 쓰는 것이 행렬곱(ex. Z @ w)


def 예측(Z, w, b):
    # "센서값과 가중치를 받아서 예측값을 계산해줘."
    return Z @ w + b


def 손실(Z, y, w, b):  # 01 과 완전히 같음: (실제 − 예측)² 의 평균 = MSE
    return np.mean((y - 예측(Z, w, b)) ** 2)


# 기울기(어느 쪽이 내리막)는 01 파일처럼 '살짝 밟아보기'
# 손잡이가 5개 (가중치 w 4개 + 보정치 b 1개) => 다섯 번 밟아보기
# 편미분 => 손잡이 여러 개 중 '하나'만 살짝 움직였을 때 손실이 변하는 정도

h = 0.0001


def 기울기_밟아보기(Z, y, w, b):
    # "가중치(w)를 조금 움직이면 손실이 어떻게 변하지?"
    gw = np.zeros(len(w))  # np.zeros(4) = [0, 0, 0, 0] => 결과 담을 빈 칸 4개
    for j in range(len(w)):  # j = 0,1,2,3 : j 번째 손잡이만 움직여 본다
        w_plus, w_minus = w.copy(), w.copy()
        w_plus[j] += h  # j 번째만 살짝 키우고
        w_minus[j] -= h  # j 번째만 살짝 줄여서
        gw[j] = (손실(Z, y, w_plus, b) - 손실(Z, y, w_minus, b)) / (
            2 * h
        )  # (오른쪽 손실 − 왼쪽 손실) ÷ 거리
    gb = (손실(Z, y, w, b + h) - 손실(Z, y, w, b - h)) / (2 * h)  # b 도 한 번
    return gw, gb


def 학습(Z, y, lr=0.1, epochs=500):
    w = np.zeros(Z.shape[1])  # Z.shape[1] = 열 수 = 4. 가중치 4개를 0 에서 출발
    b = 0.0
    for _ in range(epochs):  # 500 바퀴 (에폭 500)
        gw, gb = 기울기_밟아보기(Z, y, w, b)
        w = w - lr * gw  # 경사하강 4개가 한꺼번에 '내리막 쪽으로 보폭 lr만큼'
        b = b - lr * gb
    return w, b


w, b = 학습(Z_train, y_train)  # 학습용
print("\n[4] 학습 완료 — 표준화 눈금의 가중치")
for 이름, wi in zip(특징이름, w):  # zip: 두줄을 나란히 짝지어 돌기
    print(f"{이름:6s} w = {wi:+.3f}")  # {:+.3f} = 부호 붙여 소수 3자리 (00 미리보기 ①)
print(f"절편 b = {b:.3f}")
# 절편 310 = 모든 센서가 "평균값"일 때의 예측 공정온도, 표준화했으니 z=0이 평균
# 공기온도 w=+1.79: 공기온도가 표준편차 1개 만큼 오르면 공정온도가 1.79 오른다, 나머지는 거의 0


# =====================================================================
# 5. 채점 — 학습용 점수와 시험용 점수를 '나란히'
# =====================================================================
def MSE(y, yhat):  # 손실과 같은 식. 채점용으로 이름만 따로
    return np.mean((y - yhat) ** 2)


# R². 1 에 가까울수록 좋음, 0 = 평균만 말하는 수준
def R2(y, yhat):
    return 1 - np.sum((y - yhat) ** 2) / np.sum((y - y.mean()) ** 2)


tr_pred = 예측(Z_train, w, b)  # 학습용
te_pred = 예측(Z_test, w, b)  # 시험용
print("\n[5] 채점")
print(
    f"학습용(train)  R² {R2(y_train, tr_pred):.4f}   손실 {MSE(y_train, tr_pred):.3f}"
)
print(f"시험용(test)   R² {R2(y_test, te_pred):.4f}   손실 {MSE(y_test, te_pred):.3f}")
# 학습용 0.81, 시험용 0.78 => 시험용이 살짝 낮은 것이 정상
"""
읽는 법 — 두 점수를 '같이' 봐야 합니다:
  둘이 비슷하고 둘 다 좋음        → 건강. 규칙을 배운 것
  학습용만 좋고 시험용이 뚝 떨어짐  → 과적합. 답안지를 외운 것
  둘 다 나쁨                     → 과소적합. 모델이 너무 단순하거나 센서가 부족
어림 기준: R² 차이가 0.05 안이면 정상, 0.10 넘으면 의심. (법칙은 아니고 경보선)
"""
# 과적합 = 학습 데이터를 '외워서' 학습 점수는 좋은데 새 데이터만 틀리는 상태
#         => 기출문제만 달달 외운 학생, 모의고사(학습용) 100점 / 수능(시험용) 60점
#         => 과적합이 나면? -> 현장에 넣는 순간, 점수가 무너짐. 학습 점수만 보고 배포하면 사고 날 가능성 있음
# 과소적합 = 덜 배워서 학습 점수부터 나쁜 상태, 공부를 안 한 학생
#         => 과소적합이 나면? -> 아예 못 맞힘, 센서를 더 넣거나, 더 오래 걷거나, 더 유연한 모델이 필요
# 왜 굳이 시험용을 따로 보나? 학습 점수는 '외웠는지 배웠는지' 구별을 못함 -> 시험용만 구별해줌

print("    시험용 앞 6대: 예측 vs 실제")
for p, t in zip(te_pred[:6], y_test[:6]):
    print(f"      예측 {p:7.2f}   실제 {t:7.2f}   (차이 {t - p:+.2f})")


