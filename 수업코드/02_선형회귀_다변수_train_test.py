# 표준화 눈금이라 네 가중치가 '같은 자'로 잰 값이다 => 그래서 크기를 비교할 수 있음
# (원래 눈금이면 회전수 w는 '1rpm 당', 토크 w는 '1Nm 당'이라 비교 의미 없음)

print("\n[6] 영향력 순위 (가중치 절댓값 큰 순)")
# key=lamda t: -abs(t[1]) = "짝의 두 번째(w)의 절댓값이 큰 순"
for 이름, wi in sorted(zip(특징이름, w), key=lambda t: -abs(t[1])):
    # 가중치의 절댓값이 큰 센서부터 정렬한다.
    print(
        f"    {이름:6s} {wi:+.3f}   {'높을수록 공정온도 ↑' if wi > 0 else '높을수록 공정온도 ↓'}"
    )  # 한 줄 if (00 미리보기 ⑤)
# 공기온도가 압도적, 나머지는 거의 0
# => 즉, 공정온도는 사실상 공기온도 하나로 정해진다

