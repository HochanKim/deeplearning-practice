# 이번엔 '둘 중 하나 (고장 1 / 정상 0)'을 맞힙니다 => 분류

# 바뀌는 건 두 가지뿐이고, 걷는 방법(경사하강)은 그대로
# 1) 직선 값을 0~1 사이의 '확률'로 바꾼다 (sigmoid라는 S자 함수)
# 2) 손실을 '확률용 자'로 바꾼다 (맞으면 벌 작게, 확신하고 틀리면 벌 크게)
# 3) 마지막에 "정확도 98%인데 쓸모없는 모델"이 왜 생기는지 직접 겪어본다

import os
import numpy as np
import pandas as pd

DATA = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "수업용데이터"
)  # data/수업용데이터/
df = pd.read_csv(os.path.join(DATA, "11_설비센서_ai4i.csv"), encoding="utf-8-sig")


# =====================================================================
# 1. 문제 정의 — 분류란 무엇인가, 그리고 이 데이터의 함정
# =====================================================================
# 분류 = 맞히려는 답이 '숫자'가 아니라 '종류'인 문제, '고장이냐 정상이냐', '양품이나 불량이나'
# 종류가 두 가지면 '이진 분류', 세 가지 이상이면 '다중 분류', 오늘은 이진 분류
#
# 회귀와 뭐가 다른가? 회귀는 "308.8도" 처럼 숫자를 말하고, 분류는 "고장"처럼 편을 고른다
# 왜 하나? => 현장에선 "몇 도냐?"보다 "이거 멈춰야 하냐? 아니냐?"가 더 자주 필요한 질문이라서

특징이름 = ["공기온도", "회전수", "토크", "공구마모"]
X = df[특징이름].values.astype(float)  # 입력은 02 와 똑같은 센서 4개
y = df["고장여부"].values.astype(
    float
)  # 정답만 바뀜: 고장 1.0 / 정상 0.0 (계산용으로 실수형)

print(
    "[1] 고장 개수:", int(y.sum()), "/ 전체", len(y), f"→ 고장 비율 {y.mean():.1%}"
)  # {:.1%} = 백분율로 소수 1자리
# y의 1의 개수 => 고장 대수, y.mean() => 1의 비율 => 고장 비율. 0/1 정답은 이렇게 세면 편하다
# 불균형 = 한쪽 편이 압도적으로 많은 샅애, 여기선 고장 4%: 정상 96%
# 함정) 고장이 4% 뿐이라 '무조건 정상!' 이라고만 답해도 정확도 96%가 나옴
# => 그래서 이 파일 끝에서 '정확도 말고 무엇을 봐야 하나'를 배운다 => 제조 데이터는 거의 다 불균형

print("=" * 70)
print(
    "    고장 난 설비의 평균 공구마모:",
    round(df[df.고장여부 == 1]["공구마모"].mean(), 1),
    "/ 정상 설비:",
    round(df[df.고장여부 == 0]["공구마모"].mean(), 1),
)
print(
    "    고장 난 설비의 평균 토크    :",
    round(df[df.고장여부 == 1]["토크"].mean(), 1),
    "/ 정상 설비:",
    round(df[df.고장여부 == 0]["토크"].mean(), 1),
)
print("=" * 70)
# df[df.고장여부 == 1] => 고장난 행만, 그 행들의 공구마모 평균
# 고장 난 설비믄 공구마모가 두 배, 토크(torque)도 크다, 이 차이를 모델이 스스로 배우게 만드는게 목표

# =====================================================================
# 2. 나누기 + 표준화 — 02 와 똑같이 (단, 고장이 양쪽에 골고루 들어가게)
# =====================================================================
# 고장이 8대뿐이라 그냥 무작위로 나누면 시험용에 고장이 0대일 수 있다 => 그러면 체점 자체가 안 됨
# 그래서 고장 설비와 정상 설비를 '따로' 70:30으로 나눈 뒤 합친다 (사이킷런에선 stratify 한 단어)

rng = np.random.RandomState(3)  # 무작위 고정 (02 와 같은 이유)

# np.where(조건)[0] = 조건이 참인 '행 번호' 목록 => 고장 8대 번호를 섞음
고장idx = rng.permutation(np.where(y == 1)[0])

# 정상 192대 번호를 섞음
정상idx = rng.permutation(np.where(y == 0)[0])

# concatenate => 두 목록을 이어 붙이기, 학습: 고장 6 + 정상 134 = 140
tr = np.concatenate([고장idx[:6], 정상idx[:134]])
te = np.concatenate([고장idx[6:], 정상idx[134:]])  # 시험: 고장 2 + 정상 58 = 60
X_train, X_test, y_train, y_test = (
    X[tr],
    X[te],
    y[tr],
    y[te],
)  # 번호로 행 골라내기 (02 2번)
print(
    "\n[2] 학습용",
    len(tr),
    "대 (고장",
    int(y_train.sum()),
    ") / 시험용",
    len(te),
    "대 (고장",
    int(y_test.sum()),
    ")",
)

mu, sd = X_train.mean(axis=0), X_train.std(axis=0)
# 표준화는 학습용 통계로만 (02 파일 규칙 그대로)
Z_train = (X_train - mu) / sd
Z_test = (X_test - mu) / sd
# => 분류에서도 표준화? 걷는 방법이 같으니 이유도 같다, 회전수 1500이 있으면 학습률 하나로 못 걷는다


# =====================================================================
# 3. 직선값을 확률로 — sigmoid
# =====================================================================
# 02 파일의 직선값(Z @ w + b)은 -50도 되고 +300도 된다, "고장 확률이 300%"는 말이 안됨
# => 그래서 어떤 수든 0~1 사이로 눌러 주는 S자 함수를 하나 통과 => 이게 바로 'sigmoid' 함수
def sigmoid(z):
    return 1 / (
        1 + np.exp(-z)
    )  # np.exp(x) = e의 X제곱, 그냥 "아주 빨리 커지는 함수"로만 알면 된다


print("=" * 70)
print("\n[3] sigmoid 맛보기 — 아무 수나 0~1 로")
for z in [-5, -2, 0, 2, 5]:
    print(f"    sigmoid({z:+d}) = {sigmoid(z):.3f}")  # {:+d} = 부호 붙인 정수
# 음수면 0쪽, 0이면 딱 0.5, 양수면 1쪽으로 => 아무리 큰 수를 넣어도 1을 못 넘고, 아무리 작은 수를 넣어도 0을 못 넘음
#
# sigmoid(시그모이드) = 아무 숫자나 0~1 사이 확률로 눌러 주는 S자 함수
# 로지스틱 회귀 = 선형모델(직선) + sigmoid. 이름에 '회귀'가 들어 있지만 하는 일은 *분류*
# 역사적으로 붙은 이름이라 헷갈리는데, "직선으로 점수를 메기고 -> sigmoid로 확률 바꾸고 -> 임계값 넘으면 고장"이 전부


def 확률(Z, w, b):
    return sigmoid(
        Z @ w + b
    )  # 설비마다 '고장일 확률' 하나씩. 02 의 예측() 에 sigmoid 만 씌운 것


# =====================================================================
# 4. 확률용 손실 — 맞으면 벌 작게, 확신하고 틀리면 벌 크게
# =====================================================================
# 회귀의 MSE(제곱 평균)는 확률 문제엔 잘 안 맞는다 => 확률엔 '확률용 자'를 사용, 규칙은 이것뿐
# 정답이 고장(1)인데 내가 "고장 확률 0.99" -> 벌점 아주 작음 (거의 맞힘)
# 정답이 고장(1)인데 내가 "고장 확률 0.01" -> 벌점 아주 큼 (확신하고 틀림)
# 정답이 정상(0)인데 반대로 (정상일 확률 = 1 - p로 본다)
# 벌점을 만드는 함수가 -log(p)이다 => log는 몰라도 된다, 표만 보면 해결
print("=" * 70)
print("\n[4] 정답이 '고장'일 때, 내가 말한 고장 확률에 따른 벌점")
for p in [0.99, 0.7, 0.5, 0.1, 0.01]:
    print(f"    p={p:<5} → 벌점 {-np.log(p):.3f}")
# 0.99 -> 0.01 (거의 0), 0.5 -> 0.69 (반반은 중간 벌)
# 0.01 -> 4.6 (폭발), '자신 있게 틀리는 것'을 크게 벌한다
# np.log(x) = "e를 몇 제곱해야 x가 되나" 여기선 그냥 "p가 0에 가까울수록 폭발하는 벌점 계산기"
# 로그손실(log loss) = 위 벌점을 설비 전체에 대해 평균 낸 것, 분류용 손실 함수
# 다른 이름: 이진 교차 엔트로피, 파이토치에선 이 이름으로 나온다


def 손실(Z, y, w, b):
    # np.clip(값, 최소, 최대) = 범위 밖이면 잘라냄, p가 딱 0이면 log(0)이 무한대라 살짝 안으로
    p = np.clip(확률(Z, w, b), 1e-12, 1 - 1e-12)

    # 읽는 법: 정답 y가 1이면 (1-y)=0이라 뒤 항이 사라져 -log(p)만 남고,
    #          정답 y가 0이면 y=0이라 앞 항이 사라져 -log(1-p)만 남는다, 위 표 그대로
    return -np.mean(y * np.log(p) + (1 - y) * np.log(1 - p))


# =====================================================================
# 5. 학습 — 경사하강 그대로 (01·02 와 한 글자도 안 다름)
# =====================================================================
# 손실 함수만 바뀌었지 '살짝 밟아보고 내리막으로 한 걸음'은 똑같다. 함수 이름까지 그대로
# 01 파일에서 '선형회귀엔 공식이 있다'고 했는데, 로지스틱 회귀부터는 공식이 없다
# => 걷는 것만이 유일한 방법, 그래서 경사하강을 손으로 배움
h = 0.0001


def 기울기_밟아보기(Z, y, w, b):  # 02 4번와 동일 (편미분 5번 = 그래디언트)
    gw = np.zeros(len(w))
    for j in range(len(w)):
        w1, w2 = w.copy(), w.copy()
        w1[j] += h
        w2[j] -= h
        gw[j] = (손실(Z, y, w1, b) - 손실(Z, y, w2, b)) / (2 * h)
    gb = (손실(Z, y, w, b + h) - 손실(Z, y, w, b - h)) / (2 * h)
    return gw, gb


def 학습(Z, y, lr=0.5, epochs=2000, 보여주기=True):
    w = np.zeros(Z.shape[1])
    b = 0.0
    for epoch in range(epochs):
        gw, gb = 기울기_밟아보기(Z, y, w, b)
        w = w - lr * gw  # 경사하강
        b = b - lr * gb
        if (
            보여주기 and epoch % 400 == 0
        ):  # 400 바퀴마다 손실 출력. % = 나머지, 400 으로 나눠 떨어질 때만
            print(f"    epoch {epoch:4d}  손실 {손실(Z, y, w, b):.4f}")
    return w, b


# 왜 lr = 0.5, epochs=2000 (2000 바퀴) => 로그손실은 MSE보다 언덕이 완만해서 보폭을 키우고 오래 걸어야 바닥에 닿는다
# lr을 0.1로 두면 2000 바퀴로 부족하고, 5.0으로 올리면 튄다(발산)
print("=" * 70)
print("\n[5] 학습 (손실이 줄어드는 걸 보세요)")
w, b = 학습(Z_train, y_train)
# 0.59 -> 0.118 -> 0.116 -> ... 400바퀴 만에 거의 다 내려오고 그 뒤는 미세 조정
# 이 모양이 '잘 걷고 있다'는 신호
print("    표준화 눈금 가중치:")
for 이름, wi in sorted(zip(특징이름, w), key=lambda t: -abs(t[1])):
    print(
        f"      {이름:6s} {wi:+.3f}  {'클수록 고장 확률 ↑' if wi > 0 else '클수록 고장 확률 ↓'}"
    )
# 공구마모가 압도적(+2.4) -> "마모가 심할수록 고장", 위에서 본 관찰(224 vs 113)과 같습니다
# 나머지 셋은 학습용에 고장이 6대뿐이라 값이 흔들린다 -> 데이터가 적을 때 가중치 해석은 조심

# =====================================================================
# 6. 확률 → 판정, 그리고 채점
# =====================================================================
# 모델이 내놓는 건 '확률'(0.53, 0.23, ...) 입니다. 현장에선 "그래서 멈춰? 말아?"를 원한다
# => 선을 하나 그어 잘라야 함
#
# 임계값 = 확률을 고장/정상으로 자르는 선, 일단 상식대로 0.5를 시작
# 판정 = 확률에 임계값을 적용해 낸 최종 답 (0 또는 1)

p_test = 확률(Z_test, w, b)  # 시험용 60대의 고장 확률
# => (배열 >= 0.5)는 True/False 배열 -> astype(int)로 1/0으로 바꿈
판정 = (p_test >= 0.5).astype(int)


print("\n[6] 시험용 60대 중 확률이 높은 순 8대")
순위 = np.argsort(
    -p_test
)  # argsor = "작은 순으로 정렬했을 때 번호" 앞에 -를 붙여 큰 순

print("    고장확률  판정  실제")
for i in 순위[:8]:
    print(f"    {p_test[i]:.3f}     {판정[i]}     {int(y_test[i])}")
# 1등 (0.528)은 진짜 고정 -> 잡았다.
# 5등 (0.232)도 진짜 고장인데 0.5 아래라 '정상' 판정 -> 놓쳤다

# 정확도 = 판정이 실제와 같은 비율 (맞힌 대수 / 전체 대수)
# 판정 == y_test 는 True/False 60개, 그 평균 = True 의 비율
정확도 = np.mean(판정 == y_test)
print(f"\n    정확도: {정확도:.3f}")


# =====================================================================
# 7. 정확도의 함정 — 네 칸으로 나눠 봐야 보인다
# =====================================================================
# 정확도는 "몇 개 맞췄나" 하나만 센다 => "어떻게 틀렸나"는 보이지 않는다, 그래서 네 칸으로 쪼갬
# 혼동행렬 = 맞고 틀림을 '어떻게' 틀렸는지까지 네 칸으로 센 표
#
# TP: 고장을 고장이라 한다 -> 잘 잡음
# FN: 고장을 정상이라고 함 -> 놓침 (※ 제조에서 제일 위험 -> 설비 멈춤, 리콜 등)
# FP: 정상을 고장이라 함 -> 경보 오작동 (재검사 한 번)
# TN: 정상을 정상이라 함 -> 잘 통과함
def 네칸(y, 판정):
    TP = int(((y == 1) & (판정 == 1)).sum())
    FN = int(((y == 1) & (판정 == 0)).sum())
    FP = int(((y == 0) & (판정 == 1)).sum())
    TN = int(((y == 0) & (판정 == 0)).sum())  # .sum() 으로 True 개수 세기
    return TP, FN, FP, TN


TP, FN, FP, TN = 네칸(y_test, 판정)
print("\n[7] 혼동행렬 (임계값 0.5)")
print(f"    고장 {int(y_test.sum())}대 중  잡음(TP) {TP}  놓침(FN) {FN}")
print(f"    정상 {int((y_test == 0).sum())}대 중 통과(TN) {TN}  헛경보(FP) {FP}")

# 재현율 = 실제 고장 중 잡아낸 비율
# => TP / (TP + FN), "놓치지 않았나?" => 제조에선 제일 중요
재현율 = TP / (TP + FN) if TP + FN else 0

# 정밀도 = 고장이라 한 것 중 진짜 비율
# => TP / (TP+FP), "헛 경보가 적나?"
# ==> 둘은 시소와 같음, 의심스러우면 전부 고장으로 판단, 정밀도가 떨어짐 (확실할 때만 고장이라 하면 반대)

정밀도 = TP / (TP + FP) if TP + FP else 0
print(f"    재현율 {재현율:.2f}  정밀도 {정밀도:.2f}")
# 재현율 0.5 = 고장 2대 중 1대만 잡음, 정밀도 1.00 => 고장이라 한 1대는 진짜

게으른판정 = np.zeros_like(y_test, dtype=int)
# zeros_like(y) = y와 같은 길이의 0 배열, 60대 전부 '정상'
print(
    f"\n    [비교] 무조건 정상이라 답하면 → 정확도 {np.mean(게으른판정 == y_test):.3f}, 재현율 0.00 (고장 전부 놓침)"
)
# 순서가 중요, 반드시 이 순서대로 해야 함
