# 5. 지저분한 데이터 다루기 — 12_제조센서_전처리.csv
# =====================================================================
dirty = pd.read_csv(path("12_제조센서_전처리.csv"), encoding="utf-8-sig")
print("=" * 60)
print("[5] 지저분한 데이터 원본")
print(dirty)

print()
print("[5-1] 결측(NaN) 개수 — 열마다")
print(
    dirty.isna().sum()
)  # isna() = 비었나? → True/False 표.  sum() = True 를 1 로 세서 합계

print()
print("[5-2] 이상값 — 물리적으로 말이 안 되는 값 찾기")
print("    회전수가 음수인 행:")
print(dirty[dirty["회전수"] < 0])  # 회전수 -50 → 센서 오류. 음수 rpm 은 존재하지 않음
print("    진동이 유난히 큰 행:")
print(
    dirty[dirty["진동"] > 10]
)  # 진동 15.2 → 다른 행은 3 근처. 센서 오류일 수도, 진짜 설비 이상일 수도

print()
print("[5-3] 중복 행 — 같은 측정이 두 번 들어간 경우")
print(
    "    중복 행 수:", dirty.duplicated().sum()
)  # duplicated() = 앞에 똑같은 행이 있었나 True/False
print(
    dirty[dirty.duplicated(keep=False)]
)  # keep=False → 중복된 짝을 둘 다 보여 줌 (측정ID 8 이 두 번)

clean = dirty.copy()  # 원본은 건드리지 않는 습관 (copy = 복사본)
clean = clean.drop_duplicates()  # 중복 제거
clean.loc[clean["회전수"] < 0, "회전수"] = np.nan
for 열 in ["온도", "압력", "회전수"]:
    중앙값 = clean[열].median()  # NaN 은 알아서 빼고 계산해 줌
    clean[열] = clean[열].fillna(중앙값)  # fillna = 빈 칸을 이 값으로 채워라
    print(f"    {열}: 결측을 중앙값 {중앙값} 로 채움")

print()
print("[5-4] 처리 후")
print(clean)
print("    결측 남은 개수:", int(clean.isna().sum().sum()), "/ 행 수:", len(clean))


