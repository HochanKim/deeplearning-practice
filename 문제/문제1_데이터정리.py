print("[1-4] 데이터가 말을 건다")

sensor_columns = ["공기온도", "공정온도", "회전수", "토크", "공구마모"]

print("(a)")
# 전체 고장 비율
error_ratio = df["고장여부"].mean()
print(f"전체 고장 비율: {error_ratio:.4f}")

# 타입별로 묶어서 고장 비율 계산
type_error_ratio = df.groupby("타입")["고장여부"].mean()
print("타입별 고장 비율:")
print(type_error_ratio.round(4))

print()
print("(b)")
# 고장여부로 묶고, 다섯 센서의 평균을 계산
sensor_avg = df.groupby("고장여부")[sensor_columns].mean()

# 행과 열을 뒤집어 정상-고장 평균을 나란히 배치
compare_table = sensor_avg.T.rename(columns={0: "정상", 1: "고장"})
print(compare_table.round(2))

print()
print("(c)")
# 다섯 센서 사이의 상관계수에서 토크와의 관계만 선택
torque_corr = df[sensor_columns].corr()["토크"]

# 토크와 자기 자신의 상관계수는 항상 1이므로 제외
torque_corr = torque_corr.drop("토크")

# 절댓값이 가장 큰 센서의 이름 찾기
strong_sensor = torque_corr.abs().idxmax()

# 원래 부호가 있는 상관계수 가져오기
corr_co = torque_corr[strong_sensor]

print("토크와의 상관계수:")
print(torque_corr.round(4))
print(f"가장 강한 센서: {strong_sensor}, 상관계수: {corr_co:.4f}")
