print("[1-3] 고치기")
# 복사본 생성
df_copy = df

# 중복 데이터 제거
df_copy = df.drop_duplicates().copy()
print("중복 제거 후:", df_copy.shape)

# 공기온도를 '켈빈'으로 변환
unit_error = df_copy["공기온도"] < 100
df_copy.loc[unit_error, "공기온도"] = (
    df_copy.loc[unit_error, "공기온도"] + 273.15
).round(1)

# 회전수 0을 결측값으로 바꾸기
df_copy.loc[df["회전수"] == 0, "회전수"] = float("nan")

# 결측을 '중앙값'으로 메우기
for column in df.select_dtypes(include="number").columns:
    # 각 데이터 열들의 중앙값 구하기
    middle_value = df_copy[column].median()
    # 결측치를 중앙값으로 채우기
    df_copy[column] = df_copy[column].fillna(middle_value)
# 처리 후 남은 결측값 개수 확인
print("남은 결측:", df_copy.isna().sum().sum())

print("공기온도 범위:", df_copy["공기온도"].min(), "~", df_copy["공기온도"].max())
print("회전수 최솟값:", df_copy["회전수"].min())

