import math


def g(z):
    # 시그모이드 : 어떤 값이든 0~1 사이로 'S자' 로 눌러 준다.
    # 자세한 건 2편에서
    return 1 / (1 + math.exp(-z))


print("\n[활성화 함수 g 맛보기 - S자로 눌러 준다]")
print("g(-2) =", round(g(-2), 4))  # → g(-2) = 0.1192
print("g( 0) =", round(g(0), 4))  # → g( 0) = 0.5
print("g( 2) =", round(g(2), 4))  # → g( 2) = 0.8808
# 큰 음수는 0쪽, 0은 딱 0.5, 큰 양수는 1쪽. 직선이 아니라 살짝 휘죠?
# 이 '휨' 이 층을 쌓았을 때 U자 같은 곡선을 만들어 내는 재료입니다.

print()

W1, b1 = 0.5, -1.0  # 은닉 뉴런1
W2, b2 = -0.3, 2.0  # 은닉 뉴런2
V1, V2, c = 1.5, -1.0, 0.4  # 출력층


def 순전파(x):
    # x 하나가 들어와 ŷ 하나가 나오기까지, 위 그림 그대로 앞으로 흐른다.
    z1 = W1 * x + b1  # 뉴런1 가중합
    z2 = W2 * x + b2  # 뉴런2 가중합
    a1 = g(z1)  # 뉴런1 활성화
    a2 = g(z2)  # 뉴런2 활성화
    y_hat = V1 * a1 + V2 * a2 + c  # 출력 (선형)
    return y_hat, z1, z2, a1, a2  # 중간값도 같이 돌려줘 눈으로 확인


y_hat, z1, z2, a1, a2 = 순전파(2.0)
print("\n[순전파 손계산 대조 · x=2.0]")
print(
    "z1 =", round(z1, 4), " a1 = g(z1) =", round(a1, 4)
)  # → z1 = 0.0 a1 = g(z1) = 0.5
print(
    "z2 =", round(z2, 4), " a2 = g(z2) =", round(a2, 4)
)  # → z2 = 1.4 a2 = g(z2) = 0.8022
print("ŷ =", round(y_hat, 4))  # → ŷ = 0.3478
# 손으로 구한 0.3478 과 코드가 딱 맞습니다.
# 층이 여러 개여도 이 흐름의 반복일 뿐이에요 — 가중합, 활성화, 다시 가중합.
# 이 '앞으로 흐르기' 가 순전파고, 신경망이 예측을 뽑는 방식입니다.
